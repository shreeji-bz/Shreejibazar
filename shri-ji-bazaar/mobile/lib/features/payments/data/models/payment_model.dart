import '../../domain/entities/payment_entity.dart';

class PaymentModel extends PaymentEntity {
  PaymentModel({
    required super.id,
    required super.userId,
    super.processedBy,
    required super.type,
    required super.amount,
    required super.currency,
    required super.method,
    required super.status,
    super.referenceId,
    super.referenceType,
    super.notes,
    super.adminNotes,
    super.balanceBefore,
    super.balanceAfter,
    super.approvedAt,
    super.completedAt,
    required super.createdAt,
    super.updatedAt,
    super.txnId,
    super.utrNumber,
    super.screenshotUrl,
    super.provider,
    super.rejectionReason,
    super.bankName,
    super.accountNumber,
    super.ifscCode,
    super.accountHolderName,
  });

  factory PaymentModel.fromJson(Map<String, dynamic> json) {
    return PaymentModel(
      id: json['id'] as String? ?? '',
      userId: json['user_id'] as String? ?? '',
      processedBy: json['processed_by'] as String?,
      type: (json['type'] as String? ?? 'deposit'),
      amount: (json['amount'] as num?)?.toDouble() ?? 0.0,
      currency: json['currency'] as String? ?? 'INR',
      method: (json['method'] as String? ?? 'upi'),
      status: (json['status'] as String? ?? 'pending'),
      referenceId: json['reference_id'] as String?,
      referenceType: json['reference_type'] as String?,
      notes: json['notes'] as String?,
      adminNotes: json['admin_notes'] as String?,
      balanceBefore: json['balance_before'] != null ? (json['balance_before'] as num).toDouble() : null,
      balanceAfter: json['balance_after'] != null ? (json['balance_after'] as num).toDouble() : null,
      approvedAt: json['approved_at'] != null ? DateTime.parse(json['approved_at'] as String) : null,
      completedAt: json['completed_at'] != null ? DateTime.parse(json['completed_at'] as String) : null,
      createdAt: json['created_at'] != null ? DateTime.parse(json['created_at'] as String) : DateTime.now(),
      updatedAt: json['updated_at'] != null ? DateTime.parse(json['updated_at'] as String) : null,
      txnId: json['txn_id'] as String?,
      utrNumber: json['utr_number'] as String?,
      screenshotUrl: json['screenshot_url'] as String?,
      provider: json['provider'] as String? ?? 'manual',
      rejectionReason: json['rejection_reason'] as String?,
      bankName: json['bank_name'] as String?,
      accountNumber: json['account_number'] as String?,
      ifscCode: json['ifsc_code'] as String?,
      accountHolderName: json['account_holder_name'] as String?,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'user_id': userId,
      if (processedBy != null) 'processed_by': processedBy,
      'type': type,
      'amount': amount,
      'currency': currency,
      'method': method,
      'status': status,
      if (referenceId != null) 'reference_id': referenceId,
      if (referenceType != null) 'reference_type': referenceType,
      if (notes != null) 'notes': notes,
      if (adminNotes != null) 'admin_notes': adminNotes,
      if (balanceBefore != null) 'balance_before': balanceBefore,
      if (balanceAfter != null) 'balance_after': balanceAfter,
      if (approvedAt != null) 'approved_at': approvedAt!.toIso8601String(),
      if (completedAt != null) 'completed_at': completedAt!.toIso8601String(),
      'created_at': createdAt.toIso8601String(),
      if (updatedAt != null) 'updated_at': updatedAt!.toIso8601String(),
      if (txnId != null) 'txn_id': txnId,
      if (utrNumber != null) 'utr_number': utrNumber,
      if (screenshotUrl != null) 'screenshot_url': screenshotUrl,
      'provider': provider ?? 'manual',
      if (rejectionReason != null) 'rejection_reason': rejectionReason,
      if (bankName != null) 'bank_name': bankName,
      if (accountNumber != null) 'account_number': accountNumber,
      if (ifscCode != null) 'ifsc_code': ifscCode,
      if (accountHolderName != null) 'account_holder_name': accountHolderName,
    };
  }

  PaymentModel copyWith({
    String? id,
    String? userId,
    String? processedBy,
    String? type,
    double? amount,
    String? currency,
    String? method,
    String? status,
    String? referenceId,
    String? referenceType,
    String? notes,
    String? adminNotes,
    double? balanceBefore,
    double? balanceAfter,
    DateTime? approvedAt,
    DateTime? completedAt,
    DateTime? createdAt,
    DateTime? updatedAt,
    String? txnId,
    String? utrNumber,
    String? screenshotUrl,
    String? provider,
    String? rejectionReason,
    String? bankName,
    String? accountNumber,
    String? ifscCode,
    String? accountHolderName,
  }) {
    return PaymentModel(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      processedBy: processedBy ?? this.processedBy,
      type: type ?? this.type,
      amount: amount ?? this.amount,
      currency: currency ?? this.currency,
      method: method ?? this.method,
      status: status ?? this.status,
      referenceId: referenceId ?? this.referenceId,
      referenceType: referenceType ?? this.referenceType,
      notes: notes ?? this.notes,
      adminNotes: adminNotes ?? this.adminNotes,
      balanceBefore: balanceBefore ?? this.balanceBefore,
      balanceAfter: balanceAfter ?? this.balanceAfter,
      approvedAt: approvedAt ?? this.approvedAt,
      completedAt: completedAt ?? this.completedAt,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      txnId: txnId ?? this.txnId,
      utrNumber: utrNumber ?? this.utrNumber,
      screenshotUrl: screenshotUrl ?? this.screenshotUrl,
      provider: provider ?? this.provider,
      rejectionReason: rejectionReason ?? this.rejectionReason,
      bankName: bankName ?? this.bankName,
      accountNumber: accountNumber ?? this.accountNumber,
      ifscCode: ifscCode ?? this.ifscCode,
      accountHolderName: accountHolderName ?? this.accountHolderName,
    );
  }
}
